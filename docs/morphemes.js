  /* 启发式构词拆解：
   *   1) 从词首匹配最长前缀；
   *   2) 从词尾匹配最长后缀；
   *   3) 在剩余词干中匹配最长词根；
   *   返回 { parts:[{type,text,meaning}], stem } 或 null。
   * 置信规则：至少命中「词根」或「前缀+后缀」才返回，降低纯词缀误判。 */
  function analyze(word) {
    if (!word) return null;
    const w = String(word).toLowerCase().replace(/[^a-z]/g, '');
    if (w.length < 4) return null;

    const parts = [];
    let rest = w;

    // 前缀（最长优先）
    const preKeys = Object.keys(prefixes).sort((a, b) => b.length - a.length);
    for (const p of preKeys) {
      if (rest.startsWith(p) && rest.length - p.length >= 2) {
        parts.push({ type: 'prefix', text: p, meaning: prefixes[p] });
        rest = rest.slice(p.length);
        break;
      }
    }

    // 后缀（最长优先）
    const sufKeys = Object.keys(suffixes).sort((a, b) => b.length - a.length);
    for (const s of sufKeys) {
      if (rest.endsWith(s) && rest.length - s.length >= 2) {
        parts.push({ type: 'suffix', text: s, meaning: suffixes[s] });
        rest = rest.slice(0, rest.length - s.length);
        break;
      }
    }

    // 词根（剩余词干中最长匹配，优先词首）
    const rootKeys = Object.keys(roots).sort((a, b) => b.length - a.length);
    let rootMatch = null;
    for (const r of rootKeys) {
      if (r.length < 3) continue;
      if (rest.startsWith(r) && rest.length - r.length <= 2) { rootMatch = r; break; }
    }
    if (!rootMatch) {
      for (const r of rootKeys) {
        if (r.length < 3) continue;
        if (rest.includes(r) && r.length >= Math.min(rest.length, 4)) { rootMatch = r; break; }
      }
    }
    if (rootMatch) {
      parts.push({ type: 'root', text: rootMatch, meaning: roots[rootMatch] });
    }

    const hasPrefix = parts.some((p) => p.type === 'prefix');
    const hasSuffix = parts.some((p) => p.type === 'suffix');
    const hasRoot = parts.some((p) => p.type === 'root');

    // 置信门槛：必须有词根，或同时有前缀+后缀
    if (!hasRoot && !(hasPrefix && hasSuffix)) return null;

    return { word: w, parts: parts, stem: rest };
  }

  window.analyzeMorpheme = analyze;
